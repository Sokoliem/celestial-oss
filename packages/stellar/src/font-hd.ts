// ── Braille Characters (U+2800-U+28FF) ──────────────────────────────────
// Each braille char encodes 8 dots in a 2x4 grid via its low 8 bits.
// Dot positions: bit0=(0,0) bit1=(0,1) bit2=(0,2) bit3=(1,0) bit4=(1,1)
//                bit5=(1,2) bit6=(0,3) bit7=(1,3)
// Each dot renders as a 3x3 pixel block in the 8x14 grid.

function generateBrailleGlyphs(): void {
  const DOT_W = 3,
    DOT_H = 3;
  // Left column x=0, Right column x=DOT_W+GAP_X=5
  // Rows: y=0,3,6,9 for the 4 vertical positions
  const dotMap: Array<[number, number, number]> = [
    // [bit, colOffset, rowOffset]
    [0, 0, 0],
    [1, 0, 3],
    [2, 0, 6],
    [6, 0, 9], // left column
    [3, 5, 0],
    [4, 5, 3],
    [5, 5, 6],
    [7, 5, 9], // right column
  ];

  for (let code = 0x2800; code <= 0x28ff; code++) {
    const bits = code - 0x2800;
    const rows: number[] = Array.from({ length: 14 }, () => 0);

    for (const [bit, cx, cy] of dotMap) {
      if (!(bits & (1 << bit))) continue;
      for (let dy = 0; dy < DOT_H && cy + dy < 14; dy++) {
        for (let dx = 0; dx < DOT_W && cx + dx < 8; dx++) {
          rows[cy + dy]! |= 1 << (7 - (cx + dx));
        }
      }
    }

    GLYPHS_HD[code] = rows;
  }
}

