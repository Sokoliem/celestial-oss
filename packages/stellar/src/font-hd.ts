// ── Block Elements (U+2580-U+259F) ──────────────────────────────────────

function generateBlockGlyphs(): void {
  function fill(y0: number, y1: number, x0: number, x1: number): number[] {
    const rows: number[] = Array.from({ length: 14 }, () => 0);
    for (let y = y0; y <= y1; y++) {
      for (let x = x0; x <= x1; x++) rows[y]! |= 1 << (7 - x);
    }
    return rows;
  }
  function shade(density: number): number[] {
    const rows: number[] = Array.from({ length: 14 }, () => 0);
    for (let y = 0; y < 14; y++) {
      for (let x = 0; x < 8; x++) {
        if ((x + y * 3) % Math.round(1 / density) === 0) {
          rows[y]! |= 1 << (7 - x);
        }
      }
    }
    return rows;
  }

  GLYPHS_HD[0x2580] = fill(0, 6, 0, 7); // ▀ upper half
  GLYPHS_HD[0x2584] = fill(7, 13, 0, 7); // ▄ lower half
  GLYPHS_HD[0x2588] = fill(0, 13, 0, 7); // █ full block
  GLYPHS_HD[0x258c] = fill(0, 13, 0, 3); // ▌ left half
  GLYPHS_HD[0x2590] = fill(0, 13, 4, 7); // ▐ right half
  GLYPHS_HD[0x2591] = shade(0.25); // ░ light shade
  GLYPHS_HD[0x2592] = shade(0.5); // ▒ medium shade
  GLYPHS_HD[0x2593] = shade(0.75); // ▓ dark shade
  // Fractional blocks
  GLYPHS_HD[0x2581] = fill(12, 13, 0, 7); // ▁ lower 1/8
  GLYPHS_HD[0x2582] = fill(11, 13, 0, 7); // ▂ lower 1/4
  GLYPHS_HD[0x2583] = fill(10, 13, 0, 7); // ▃ lower 3/8
  GLYPHS_HD[0x2585] = fill(6, 13, 0, 7); // ▅ lower 5/8
  GLYPHS_HD[0x2586] = fill(5, 13, 0, 7); // ▆ lower 3/4
  GLYPHS_HD[0x2587] = fill(4, 13, 0, 7); // ▇ lower 7/8
  GLYPHS_HD[0x2589] = fill(0, 13, 0, 6); // ▉ left 7/8
  GLYPHS_HD[0x258a] = fill(0, 13, 0, 5); // ▊ left 3/4
  GLYPHS_HD[0x258b] = fill(0, 13, 0, 4); // ▋ left 5/8
  GLYPHS_HD[0x258d] = fill(0, 13, 0, 2); // ▍ left 3/8
  GLYPHS_HD[0x258e] = fill(0, 13, 0, 1); // ▎ left 1/4
  GLYPHS_HD[0x258f] = fill(0, 13, 0, 0); // ▏ left 1/8
  GLYPHS_HD[0x25a0] = fill(3, 11, 1, 6); // ■ black square
}

